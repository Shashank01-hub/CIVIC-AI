CREATE DATABASE IF NOT EXISTS smart_city CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE smart_city;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('CITIZEN','ADMIN') NOT NULL DEFAULT 'CITIZEN', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS departments (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE, description TEXT
);
CREATE TABLE IF NOT EXISTS issues (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id BIGINT NOT NULL, title VARCHAR(180) NOT NULL, description TEXT NOT NULL,
 location_text VARCHAR(255) NOT NULL, latitude DOUBLE NULL, longitude DOUBLE NULL, image_url VARCHAR(500),
 ai_category VARCHAR(120), ai_priority ENUM('LOW','MEDIUM','HIGH','CRITICAL'), ai_summary TEXT,
 ai_suggested_department_id BIGINT NULL, assigned_department_id BIGINT NULL,
 status ENUM('SUBMITTED','VERIFIED','ASSIGNED','IN_PROGRESS','RESOLVED','REJECTED') NOT NULL DEFAULT 'SUBMITTED',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_issue_user FOREIGN KEY (user_id) REFERENCES users(id), CONSTRAINT fk_issue_ai_dept FOREIGN KEY (ai_suggested_department_id) REFERENCES departments(id),
 CONSTRAINT fk_issue_assigned_dept FOREIGN KEY (assigned_department_id) REFERENCES departments(id)
);
CREATE TABLE IF NOT EXISTS issue_updates (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, issue_id BIGINT NOT NULL, updated_by BIGINT NOT NULL,
 old_status ENUM('SUBMITTED','VERIFIED','ASSIGNED','IN_PROGRESS','RESOLVED','REJECTED') NOT NULL,
 new_status ENUM('SUBMITTED','VERIFIED','ASSIGNED','IN_PROGRESS','RESOLVED','REJECTED') NOT NULL,
 comment TEXT, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_update_issue FOREIGN KEY (issue_id) REFERENCES issues(id), CONSTRAINT fk_update_user FOREIGN KEY (updated_by) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS otp_verifications (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(180) NOT NULL,
 purpose VARCHAR(32) NOT NULL,
 code_hash VARCHAR(255) NOT NULL,
 expires_at TIMESTAMP NOT NULL,
 used BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_otp_email_purpose (email,purpose)
);
